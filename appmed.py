def find_hint_for_label(label: str):
    if "Άλλη πάθηση" in label:
        return {
            'documents': '• Πλήρης ιατρικός φάκελος\n• Πρόσφατη γνωμάτευση θεράποντος ιατρού',
            'coverage_waiting': 'Εκτίμηση ασφαλισιμότητας κατά περίπτωση (Underwriting)',
            'exclusion': 'Εκτίμηση ασφαλισιμότητας κατά περίπτωση',
            'premium_loading': 'Εκτίμηση ασφαλισιμότητας κατά περίπτωση',
            'rejection': 'Ανάλογα με τη βαρύτητα και την εξέλιξη της νόσου'
        }
    if label in MEDICAL_HINTS: return MEDICAL_HINTS[label]
    norm = _normalize_text(label)
    for k, v in MEDICAL_HINTS.items():
        if _normalize_text(k) == norm: return v
    return None

def render_medical_category(category_key, category_data, m_key=""):
    label = category_data['label']
    diseases = category_data['diseases'].copy()
    other_option = "Άλλη πάθηση (Περιγράψτε παρακάτω)"
    if other_option not in diseases:
        diseases.append(other_option)
        
    choice_key = f"ui_med_choice_{category_key}_{m_key}"
    saved_selections = st.session_state.client_data.get(f"med_{category_key}_{m_key}", [])
    valid_defaults = [d for d in saved_selections if d in diseases]
    
    selected = st.multiselect("Επιλέξτε παθήσεις:", diseases, default=valid_defaults, key=choice_key)
    st.session_state.client_data[f"med_{category_key}_{m_key}"] = selected

    if selected:
        for disease in selected:
            with st.expander(f"🩺 {disease}", expanded=False):
                hint_data = find_hint_for_label(disease)
                if isinstance(hint_data, dict):
                    disease_rows = []
                    documents = hint_data.get('documents', '-').strip()
                    coverage_waiting = hint_data.get('coverage_waiting', '-').strip()
                    exclusion = hint_data.get('exclusion', '-').strip()
                    premium_loading = hint_data.get('premium_loading', '-').strip()
                    rejection = hint_data.get('rejection', '-').strip()
                    
                    disease_rows.append(f"<strong>Απαραίτητα Δικαιολογητικά:</strong><br>{documents.replace('\n', '<br>')}")
                    disease_rows.append(f"<strong>Άμεση Κάλυψη/Αναμονή:</strong><br>{coverage_waiting.replace('\n', '<br>')}")
                    disease_rows.append(f"<strong>Εξαίρεση:</strong><br>{exclusion.replace('\n', '<br>')}")
                    disease_rows.append(f"<strong>Επασφάλιστρο:</strong><br>{premium_loading.replace('\n', '<br>')}")
                    disease_rows.append(f"<strong>Απόρριψη:</strong><br>{rejection.replace('\n', '<br>')}")
                    st.markdown(f"<div style='margin-bottom: 10px; font-size: 14.5px;'>{'<br><br>'.join(disease_rows)}</div>", unsafe_allow_html=True)
                else:
                    st.markdown(f"<div style='margin-bottom: 10px; font-size: 14.5px;'>Δεν υπάρχουν πληροφορίες underwriting για αυτήν την πάθηση.</div>", unsafe_allow_html=True)
                
                disease_safe_key = ''.join(e for e in disease if e.isalnum())
                note_state_key = f"note_{category_key}_{disease_safe_key}_{m_key}"
                
                st.session_state.client_data[note_state_key] = st.text_area(
                    f"Σημείωση Πελάτη (Περιγράψτε τα συμπτώματα / αγωγή):",
                    value=st.session_state.client_data.get(note_state_key, ""),
                    key=f"ui_{note_state_key}",
                    height=68
                )

